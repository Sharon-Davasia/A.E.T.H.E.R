import assert from 'node:assert/strict';
import { readFileSync, readdirSync } from 'node:fs';
import path from 'node:path';
import test from 'node:test';
import { fileURLToPath } from 'node:url';
import {
  parseExactPreview,
} from '../shared/review';
import {
  canonicalizePythonJson,
  previewIdForDigest,
  reviewDigestFor,
  reviewDigestPayloadOf,
  reviewRequestIdForDigest,
  verifyExactPreviewDigest,
} from '../shared/review-integrity';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const FIXTURE_PATH = path.join(root, 'tests', 'fixtures', 'stage2-exact-preview.golden.json');

function loadFixture(): {
  generator: string;
  synthetic_canary: string;
  preview: Record<string, unknown>;
  digest_payload_canonical_json: string;
  preview_digest: string;
  preview_id: string;
  review_request_id: string;
} {
  return JSON.parse(readFileSync(FIXTURE_PATH, 'utf8'));
}

test('golden fixture is generated by the checked-in generator and pinned to Python', () => {
  const fixture = loadFixture();
  assert.equal(fixture.generator, 'scripts/generate_stage2_golden.py');
  assert.match(fixture.preview_digest, /^[0-9a-f]{64}$/);
  assert.match(fixture.preview_id, /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/);
  assert.match(fixture.review_request_id, /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/);
});

test('Python digest payload canonicalizes byte-for-byte in the Electron contract', () => {
  const fixture = loadFixture();
  const preview = parseExactPreview(fixture.preview);
  const payload = reviewDigestPayloadOf(preview);
  assert.equal(canonicalizePythonJson(payload), fixture.digest_payload_canonical_json);
});

test('preview digest, preview ID and review request ID correspond across languages', () => {
  const fixture = loadFixture();
  const preview = parseExactPreview(fixture.preview);
  assert.equal(reviewDigestFor(preview), fixture.preview_digest);
  assert.equal(preview.previewDigest, fixture.preview_digest);
  assert.equal(previewIdForDigest(fixture.preview_digest), fixture.preview_id);
  assert.equal(reviewRequestIdForDigest(fixture.preview_digest), fixture.review_request_id);
  assert.equal(preview.previewId, fixture.preview_id);
  assert.equal(preview.reviewRequestId, fixture.review_request_id);
  assert.equal(verifyExactPreviewDigest(preview), true);
});

test('any mutation of a parser-visible field invalidates the digest', () => {
  const fixture = loadFixture();
  const mutated = {
    ...fixture.preview,
    explanation: String(fixture.preview.explanation).replace('golden', 'synthetic'),
  };
  const preview = parseExactPreview(mutated);
  assert.equal(verifyExactPreviewDigest(preview), false);

  const digestDrift = { ...fixture.preview, previewDigest: `f${fixture.preview_digest.slice(1)}` };
  const driftPreview = parseExactPreview(digestDrift);
  assert.equal(verifyExactPreviewDigest(driftPreview), false);
});

test('diff body is visible on the surface but never enters the canonical digest payload', () => {
  const fixture = loadFixture();
  assert.ok(JSON.stringify(fixture.preview).includes(fixture.synthetic_canary));
  assert.ok(!fixture.digest_payload_canonical_json.includes(fixture.synthetic_canary));
  assert.ok(!fixture.digest_payload_canonical_json.includes('unified_diff'));
});

test('renderer sources never import the node-side digest verifier', () => {
  const srcDir = path.join(root, 'src');
  const sources = readdirSync(srcDir).filter((name) => /\.(tsx?|jsx?)$/.test(name));
  assert.ok(sources.length > 0);
  for (const name of sources) {
    const content = readFileSync(path.join(srcDir, name), 'utf8');
    assert.ok(!content.includes('review-integrity'), `${name} must not import review-integrity`);
    assert.ok(!content.includes('node:crypto'), `${name} must not use node:crypto`);
  }
});
